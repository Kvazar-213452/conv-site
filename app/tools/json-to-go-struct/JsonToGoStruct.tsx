"use client";

import { useState, useCallback } from "react";
import { jsonToGoStruct, DEFAULT_OPTIONS, type GoOptions } from "./utils";
import { Code2, Lock, Copy } from "lucide-react";

import "@/style/main.css";
import "@/style/bar.css";

const EXAMPLE = `{
  "id": 1,
  "name": "Alice",
  "email": "alice@example.com",
  "active": true,
  "scores": [98, 85, 92],
  "address": {
    "street": "123 Main St",
    "city": "Springfield",
    "zip": "62701"
  }
}`;

export default function JsonToGoStruct() {
  const [input, setInput] = useState(EXAMPLE);
  const [output, setOutput] = useState("");
  const [options, setOptions] = useState<GoOptions>(DEFAULT_OPTIONS);
  const [error, setError] = useState("");
  const [copied, setCopied] = useState(false);

  const convert = useCallback(() => {
    setError("");
    if (!input.trim()) { setOutput(""); return; }
    setTimeout(() => {
      try {
        setOutput(jsonToGoStruct(input, options));
      } catch (e) {
        setError((e as Error).message);
        setOutput("");
      }
    }, 180);
  }, [input, options]);

  const clearAll = () => { setInput(""); setOutput(""); setError(""); };
  const loadExample = () => { setInput(EXAMPLE); setOutput(""); setError(""); };
  const copyOutput = () => {
    if (!output) return;
    navigator.clipboard.writeText(output);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <>
      <section className="hero" aria-labelledby="hero-heading">
        <div className="hero-eyebrow">
          <div className="hero-dot" aria-hidden="true" />
          Free · No sign-up · Runs in browser
        </div>
        <h1 id="hero-heading">
          JSON to Go <em>Struct</em>
        </h1>
        <p>
          Convert JSON to Go struct definitions with proper types, json tags,
          and nested struct generation. Paste JSON, get Go code.
        </p>
      </section>

      {error && (
        <div className="error-bar" role="alert" aria-live="assertive">
          <span aria-hidden="true">✕</span>
          <span>Error: {error}</span>
        </div>
      )}

      <section aria-label="JSON to Go Struct Converter">
        <div className="converter">
          <div className="panel">
            <div className="panel-header">
              <div className="panel-title">
                <div className="dot json" aria-hidden="true" />
                JSON Input
              </div>
              <div className="panel-actions">
                <button className="btn-ghost" onClick={loadExample}>Example</button>
                <button className="btn-ghost" onClick={() => { setInput(""); setOutput(""); }}>Clear</button>
              </div>
            </div>
            <textarea
              aria-label="JSON input"
              placeholder="Paste JSON here…"
              value={input}
              onChange={(e) => { setInput(e.target.value); setOutput(""); }}
              spellCheck={false}
              autoCorrect="off"
              autoCapitalize="off"
            />
          </div>

          <div className="panel has-output">
            <div className="panel-header">
              <div className="panel-title">
                <div className="dot go" aria-hidden="true" />
                Go Struct
                {output && <span className="success-tag">✓ converted</span>}
              </div>
              <div className="panel-actions">
                {output && <button className="btn-ghost" onClick={copyOutput}>{copied ? "Copied!" : "Copy"}</button>}
              </div>
            </div>
            <pre className="output-pre" aria-live="polite">{output || "Go struct will appear here…"}</pre>
          </div>
        </div>

        <div className="options-bar">
          <label>
            <span>Struct name:</span>
            <input
              type="text"
              value={options.structName}
              onChange={(e) => { setOptions((p) => ({ ...p, structName: e.target.value || "AutoGenerated" })); setOutput(""); }}
              style={{ width: 120, padding: "4px 8px", fontSize: 13, fontFamily: "'Geist Mono', monospace", background: "var(--color-accent-soft)", border: "1px solid var(--color-border-bright)", borderRadius: 6, color: "var(--color-text)" }}
            />
          </label>
          <label>
            <input type="checkbox" checked={options.omitempty} onChange={(e) => { setOptions((p) => ({ ...p, omitempty: e.target.checked })); setOutput(""); }} />
            omitempty
          </label>
          <label>
            <input type="checkbox" checked={options.inlineJSON} onChange={(e) => { setOptions((p) => ({ ...p, inlineJSON: e.target.checked })); setOutput(""); }} />
            Inline nested
          </label>
        </div>

        <div className="actions">
          <button className="btn-secondary" onClick={loadExample}>Load Example</button>
          <button className="btn-convert" onClick={convert} disabled={!input.trim()}>
            <Code2 size={16} aria-hidden="true" className="mr-1" /> Convert to Go
          </button>
          <button className="btn-secondary" onClick={clearAll}>Clear All</button>
        </div>
      </section>

      <section className="seo-content" aria-labelledby="about-heading">
        <h2 id="about-heading">About JSON to Go Struct Tool</h2>
        <p>
          This free online JSON to Go struct converter generates idiomatic Go struct definitions from any JSON input.
          It infers Go types (string, int64, float64, bool), generates json struct tags, handles nested objects as
          separate named structs, and supports arrays of objects. Configure the root struct name, toggle omitempty
          on json tags, and choose between inline or named nested structs. Essential for Go developers working with
          JSON APIs, configuration files, and data pipelines.
        </p>

        <h3>Why Convert JSON to Go Structs?</h3>
        <p>
          Go's type system requires explicit struct definitions for JSON unmarshaling. Writing structs by hand from
          large or nested JSON payloads is tedious and error-prone — wrong types cause runtime panics. This tool
          automates the process: paste an API response or config file, get production-ready Go code with correct
          types and json tags. Saves minutes per struct and eliminates type mismatches.
        </p>

        <h3>Key Benefits</h3>
        <ul>
          <li><strong>Type inference:</strong> Correctly maps JSON types to Go (string, int64, float64, bool, nested structs, slices)</li>
          <li><strong>JSON tags:</strong> Generates json struct tags matching the original field names</li>
          <li><strong>Nested structs:</strong> Objects within objects become named Go structs or inline structs</li>
          <li><strong>Configurable:</strong> Set struct name, toggle omitempty, choose inline vs named nested structs</li>
          <li><strong>PascalCase fields:</strong> Converts snake_case and camelCase keys to idiomatic Go PascalCase</li>
          <li><strong>Instant output:</strong> No server round-trips — runs entirely in your browser</li>
        </ul>

        <h3>Common Use Cases</h3>
        <p>
          Backend developers convert API responses (REST, GraphQL) into Go structs for client code. DevOps engineers
          generate structs for JSON config files (Terraform state, Kubernetes manifests). Data engineers create structs
          for ETL pipelines processing JSON data. Library authors build typed wrappers for third-party JSON APIs.
        </p>

        <h3>Privacy and Security</h3>
        <p>
          All conversion happens locally in your browser. Your JSON data — including API responses, configuration
          files, and production payloads — never leaves your device. No cookies, no tracking, no server uploads.
          Safe for proprietary schemas and confidential API data.
        </p>
      </section>

      <section className="features" aria-label="Features">
        {[
          { icon: <Code2 size={24} />, title: "Type inference", desc: "Maps JSON types to idiomatic Go: string, int64, float64, bool, structs, and slices." },
          { icon: <Lock size={24} />, title: "Fully private", desc: "Your JSON and API schemas never leave the browser. Safe for production data." },
          { icon: <Copy size={24} />, title: "Copy-paste ready", desc: "Generated Go structs include json tags and are ready for your codebase." },
        ].map(({ icon, title, desc }) => (
          <div className="feature" key={title}>
            <div className="feature-icon" aria-hidden="true">{icon}</div>
            <h3>{title}</h3>
            <p>{desc}</p>
          </div>
        ))}
      </section>
    </>
  );
}
